_language = "ko"


def get_language() -> str:
    return _language


def set_language(code: str) -> None:
    global _language
    if code not in LANGUAGES:
        raise ValueError(code)
    _language = code


def language_label(code: str) -> str:
    return LANGUAGE_LABELS[code]


def language_code(label: str) -> str:
    for code, name in LANGUAGE_LABELS.items():
        if name == label:
            return code
    return "ko"


def t(key: str, default: str | None = None, **kwargs: object) -> str:
    text = _STRINGS.get(_language, {}).get(key)
    if text is None:
        text = _STRINGS["ko"].get(key)
    if text is None:
        text = default if default is not None else key
    if kwargs:
        return text.format(**kwargs)
    return text


def translate_warning(warning: str) -> str:
    if warning.startswith("grace:"):
        return t("warn.grace", count=int(warning.split(":", 1)[1]))
    return t(f"warn.{warning}", default=warning)


def instrument_name(instrument: object) -> str:
    return t(f"inst.{instrument.id}.name", default=instrument.name)  # type: ignore[attr-defined]


def instrument_detail(instrument: object) -> str:
    return t(f"inst.{instrument.id}.detail", default=instrument.detail)  # type: ignore[attr-defined]


def settings_path() -> Path:
    appdata = Path.home() / "AppData" / "Roaming"
    if appdata.is_dir():
        folder = appdata / "AutomataPlayer"
    else:
        folder = Path.home() / ".automata-player"
    return folder / "settings.json"


def load_language() -> None:
    path = settings_path()
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return
    code = data.get("language")
    if code in LANGUAGES:
        set_language(code)


def save_language() -> None:
    path = settings_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"language": _language}, ensure_ascii=False, indent=2), encoding="utf-8")
